#!/usr/bin/env node
/**
 * Generate `docs/tool-catalog.md` from the live tool-factory registry.
 *
 * The registry is the only place that knows the real tool set — `createTools`
 * is a registry walk with no if-chains, and plugins register through the same
 * path as built-ins. A hand-maintained list drifts the first time someone adds
 * a tool; this cannot.
 *
 * The cross-check it performs is the useful part: each factory's real config
 * gate — read out of the factory body, not guessed from the tool id — is looked
 * up in `DEFAULT_CONFIG`. A gate with no default is a tool that exists but is
 * invisible in a fresh `config.yaml`, which is the tool-shaped version of the
 * unread-key problem the config catalog exists for.
 *
 *   node scripts/gen-tool-catalog.mjs           # write docs/tool-catalog.md
 *   node scripts/gen-tool-catalog.mjs --check   # fail if it is stale
 *
 * Requires a build (`pnpm run build`).
 */

import { readdirSync, readFileSync, statSync, writeFileSync } from "node:fs";
import { dirname, join, relative, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const OUT = join(ROOT, "docs", "tool-catalog.md");
const CHECK = process.argv.includes("--check");

const base = new URL("../packages/core/dist/", import.meta.url).href;
// Importing the index is what registers the built-ins — the registry is empty
// until their modules run their top-level side effects.
await import(`${base}index.js`);
const { toolFactoryRegistry, META_TOOL_NAMES } = await import(`${base}tools/tool-factories.js`);
const { DEFAULT_CONFIG } = await import(`${base}config.js`);

/**
 * Read a tool's real config gate out of its factory body.
 *
 * Assuming `tools.<id>` is wrong often enough to matter: `schedule` is gated by
 * `config.schedules.enabled`, and a catalog that guessed would report it as
 * missing a default it never wanted. Take the first `config.<path>` the factory
 * actually touches, which is the early-return gate in every current factory.
 */
function gateFrom(text, from) {
  const body = text.slice(from, from + 600);
  const m = body.match(/config\.([A-Za-z_$][\w$]*(?:\??\.[A-Za-z_$][\w$]*)*)/);
  if (!m) return null;
  // Drop the trailing `.enabled` — the gate is the block a user configures.
  return m[1].replace(/\?\./g, ".").replace(/\.enabled$/, "");
}

/** Find the file that calls `registerToolFactory("<id>", …)`. */
function registrationSites() {
  const sites = new Map();
  const skip = new Set(["node_modules", "dist", "ui-dist", "__tests__", ".turbo", "coverage"]);
  const walk = (dir) => {
    for (const entry of readdirSync(dir)) {
      if (skip.has(entry)) continue;
      const full = join(dir, entry);
      if (statSync(full).isDirectory()) {
        walk(full);
        continue;
      }
      if (!entry.endsWith(".ts") || entry.endsWith(".d.ts")) continue;
      const text = readFileSync(full, "utf8");
      for (const m of text.matchAll(/registerToolFactory\(\s*["'`]([^"'`]+)["'`]/g)) {
        sites.set(m[1], { file: relative(ROOT, full), gate: gateFrom(text, m.index) });
      }
    }
  };
  for (const pkg of readdirSync(join(ROOT, "packages"))) {
    const src = join(ROOT, "packages", pkg, "src");
    try {
      if (statSync(src).isDirectory()) walk(src);
    } catch {
      // No src/ in this package.
    }
  }
  return sites;
}

const sites = registrationSites();
const ids = toolFactoryRegistry.list().sort((a, b) => a.localeCompare(b));

/** Does `DEFAULT_CONFIG` ship a default at this dotted path? */
function hasDefault(path) {
  let node = DEFAULT_CONFIG;
  for (const segment of path.split(".")) {
    if (node === null || typeof node !== "object" || !Object.hasOwn(node, segment)) return false;
    node = node[segment];
  }
  return true;
}

const rows = ids.map((id) => {
  // `__custom_tools__` is the config-only escape hatch, not a real tool id.
  const synthetic = id.startsWith("__");
  const site = sites.get(id);
  const gate = synthetic ? "custom_tools" : (site?.gate ?? `tools.${id}`);
  return {
    id,
    source: site?.file ?? "—",
    gate,
    defaulted: synthetic || hasDefault(gate),
  };
});
const ungated = rows.filter((r) => !r.defaulted);

const lines = [];
lines.push("<!-- Generated by scripts/gen-tool-catalog.mjs — do not edit by hand.");
lines.push("     Regenerate with `pnpm run gen:tool-catalog`; CI verifies freshness. -->");
lines.push("");
lines.push("# Tool catalog");
lines.push("");
lines.push("Every factory in the tool-factory registry, read from the registry itself rather");
lines.push("than maintained by hand. `createTools()` is a walk over exactly this list, so if a");
lines.push("tool is here it is reachable, and if it is not here nothing will build it.");
lines.push("");
lines.push("This is the *registered* set, not the set any one agent sees: a factory returns");
lines.push("`[]` when its config gate is off or unconfigured, and an agent's `tools:` allowlist");
lines.push("narrows further.");
lines.push("");
lines.push(`Registered factories: **${rows.length}** · meta-tools always injected: **${META_TOOL_NAMES.length}**`);
lines.push("");

if (ungated.length > 0) {
  lines.push("## No default for the config gate");
  lines.push("");
  lines.push("Their config gate has no entry in `DEFAULT_CONFIG`, so the tool exists but is");
  lines.push("invisible in a fresh `config.yaml` — you can only turn it on if you already know");
  lines.push("the key. That is the right shape for an optional integration with credentials to");
  lines.push("supply, and the wrong shape for anything else; the list is here to be reviewed,");
  lines.push("not assumed broken.");
  lines.push("");
  lines.push("| Tool | Gate |");
  lines.push("| --- | --- |");
  for (const r of ungated) lines.push(`| \`${r.id}\` | \`${r.gate}\` |`);
  lines.push("");
}

lines.push("## Registered factories");
lines.push("");
lines.push("| Tool | Config gate | Default | Registered in |");
lines.push("| --- | --- | --- | --- |");
for (const r of rows) {
  lines.push(`| \`${r.id}\` | \`${r.gate}\` | ${r.defaulted ? "yes" : "**none**"} | \`${r.source}\` |`);
}
lines.push("");
lines.push("## Meta-tools");
lines.push("");
lines.push("Injected by `createMetaTools()` on every agent, outside the registry and outside");
lines.push("the `tools` config block. They are the reason an agent always has a way to");
lines.push("delegate, check a task, and read its own memory.");
lines.push("");
for (const name of META_TOOL_NAMES) lines.push(`- \`${name}\``);
lines.push("");

const generated = `${lines.join("\n").replace(/\n{3,}/g, "\n\n").trimEnd()}\n`;

if (CHECK) {
  let committed = "";
  try {
    committed = readFileSync(OUT, "utf8");
  } catch {
    console.error("gen-tool-catalog: docs/tool-catalog.md is missing. Run `pnpm run gen:tool-catalog`.");
    process.exit(1);
  }
  if (committed !== generated) {
    console.error("gen-tool-catalog: docs/tool-catalog.md is stale.");
    console.error("A tool was added, removed, or moved without the catalog being regenerated.");
    console.error("Run `pnpm run gen:tool-catalog` and commit the result.");
    process.exit(1);
  }
  console.log(`gen-tool-catalog: catalog is current (${rows.length} factories).`);
} else {
  writeFileSync(OUT, generated);
  console.log(`gen-tool-catalog: wrote docs/tool-catalog.md — ${rows.length} factories, ${ungated.length} ungated.`);
}
